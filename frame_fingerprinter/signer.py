"""
GnuPG signing and verification for frame fingerprints.

Uses the ``python-gnupg`` library (a thin subprocess wrapper around the
``gpg`` binary) to:

- Sign the ``chain_hash`` of a fingerprint with a private key.
- Verify a detached ASCII-armored signature against a ``chain_hash``.
- Generate ephemeral test key-pairs (useful for CI / unit tests).
"""

import os
import tempfile
import threading
from typing import Optional

import gnupg

__all__ = [
    "sign_chain_hash",
    "verify_signature",
    "generate_test_key",
]

# ---------------------------------------------------------------------------
# GPG instance cache
# ---------------------------------------------------------------------------
# Creating a gnupg.GPG() object is inexpensive, but it does stat the gpg
# home directory.  More importantly, caching avoids re-reading agent sockets
# on every call when a large chain is being built or verified.  Access is
# protected by a lock so the cache is safe in multi-threaded use.

_gpg_cache: dict[Optional[str], gnupg.GPG] = {}
_gpg_cache_lock = threading.Lock()


def _get_gpg(gpg_home: Optional[str] = None) -> gnupg.GPG:
    """Return a cached :class:`gnupg.GPG` instance for *gpg_home*."""
    with _gpg_cache_lock:
        if gpg_home not in _gpg_cache:
            _gpg_cache[gpg_home] = gnupg.GPG(gnupghome=gpg_home)
        return _gpg_cache[gpg_home]


def sign_chain_hash(
    chain_hash: str,
    key_fingerprint: str,
    passphrase: Optional[str] = None,
    gpg_home: Optional[str] = None,
) -> str:
    """
    Create a detached ASCII-armored GPG signature over *chain_hash*.

    Args:
        chain_hash:      The ``"sha256:<hex>"`` string to sign.
        key_fingerprint: Fingerprint (or key ID) of the signing key.
        passphrase:      Passphrase for the signing key; ``None`` if the key
                         has no passphrase.
        gpg_home:        Path to GPG home directory; ``None`` uses the default
                         ``~/.gnupg``.

    Returns:
        ASCII-armored detached signature string.

    Raises:
        :exc:`RuntimeError` if the GPG signing operation fails.
    """
    gpg = _get_gpg(gpg_home)
    result = gpg.sign(
        chain_hash.encode("utf-8"),
        keyid=key_fingerprint,
        detach=True,
        passphrase=passphrase,
    )
    if not result or not str(result):
        raise RuntimeError(
            f"GPG signing failed: {getattr(result, 'stderr', 'unknown error')}"
        )
    return str(result)


def verify_signature(
    chain_hash: str,
    signature: str,
    gpg_home: Optional[str] = None,
) -> dict:
    """
    Verify a detached GPG signature over *chain_hash*.

    The public key must already be present in the GPG keyring at *gpg_home*
    (or ``~/.gnupg`` if not specified).

    Args:
        chain_hash: The signed data (the ``"sha256:<hex>"`` string).
        signature:  ASCII-armored detached PGP signature.
        gpg_home:   Path to GPG home directory.

    Returns:
        Dict with keys:

        - ``valid``       – :class:`bool`, ``True`` iff the signature is valid.
        - ``key_id``      – Short key ID of the signing key, or ``None``.
        - ``fingerprint`` – Full key fingerprint, or ``None``.
        - ``timestamp``   – Unix timestamp of the signature, or ``None``.
        - ``username``    – UID string of the signing key, or ``None``.
        - ``status``      – Raw status string from GPG.
    """
    gpg = _get_gpg(gpg_home)

    with tempfile.NamedTemporaryFile(
        mode="w", suffix=".asc", delete=False
    ) as sig_file:
        sig_file.write(signature)
        sig_path = sig_file.name

    try:
        result = gpg.verify_data(sig_path, chain_hash.encode("utf-8"))
    finally:
        os.unlink(sig_path)

    return {
        "valid": bool(result),
        "key_id": getattr(result, "key_id", None),
        "fingerprint": getattr(result, "fingerprint", None),
        "timestamp": getattr(result, "timestamp", None),
        "username": getattr(result, "username", None),
        "status": getattr(result, "status", None),
    }


def generate_test_key(
    name: str = "Frame Fingerprinter Test",
    email: str = "test@frame-fingerprinter.local",
    passphrase: str = "",
    gpg_home: Optional[str] = None,
) -> str:
    """
    Generate an ephemeral RSA-2048 GPG key pair for testing purposes.

    .. warning::
        Do **not** use keys generated by this function for production signing.
        Use a properly generated and protected GPG key instead.

    Args:
        name:       Real-name field for the generated UID.
        email:      E-mail field for the generated UID.
        passphrase: Key passphrase (empty string for no passphrase).
        gpg_home:   Path to a temporary GPG home directory.

    Returns:
        The 40-character hex fingerprint of the generated key.

    Raises:
        :exc:`RuntimeError` if key generation fails.
    """
    gpg = _get_gpg(gpg_home)
    input_data = gpg.gen_key_input(
        key_type="RSA",
        key_length=2048,
        name_real=name,
        name_email=email,
        passphrase=passphrase,
        expire_date=0,
    )
    key = gpg.gen_key(input_data)
    if not key.fingerprint:
        raise RuntimeError("Failed to generate GPG key")
    return key.fingerprint
